/**
 * Правка часов в выбранном времени встречи: точное время не теряется.
 *
 * Выбрал клетку на карте («сб · 10:00–10:50») и дописал конец «14:00» — раньше
 * встреча уходила простым текстом и пропадала с карты, из календаря и напоминаний.
 */

import { describe, expect, it } from "vitest";

import { repick } from "@/components/pick";

const base = { value: "2026-10-03T10:00|50", text: "суббота, 3 октября · 10:00–10:50" };

describe("repick", () => {
  it("поправили конец — та же встреча, длиннее", () => {
    expect(repick(base, "суббота, 3 октября · 10:00–14:00")).toEqual({
      value: "2026-10-03T10:00|240",
      text: "суббота, 3 октября · 10:00–14:00",
    });
  });

  it("поправили начало и конец, через перерыв; дефис и точка вместо двоеточия тоже годятся", () => {
    expect(repick(base, "суббота, 3 октября · 13:10-15.10")?.value).toBe("2026-10-03T13:10|120");
  });

  it("день поменяли или дописали слова — это уже свой текст, точного времени нет", () => {
    expect(repick(base, "воскресенье, 4 октября · 10:00–14:00")).toBeNull();
    expect(repick(base, "суббота, 3 октября · 10:00–14:00 или позже")).toBeNull();
    expect(repick(base, "суббота, 3 октября · днём")).toBeNull();
  });

  it("конец раньше начала или за полночью — не встреча", () => {
    expect(repick(base, "суббота, 3 октября · 14:00–10:00")).toBeNull();
    expect(repick(base, "суббота, 3 октября · 23:00–25:00")).toBeNull();
    expect(repick(base, "суббота, 3 октября · 10:00–10:00")).toBeNull();
  });
});
